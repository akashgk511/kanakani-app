-- Kanakani schema. PostgreSQL 15 or newer.
--
-- Privacy rule for this whole file: no table stores a phone number, a real name,
-- an email address or an IP address. Phone numbers become one-way tokens
-- (HMAC-SHA256 with a server-side key) before they reach the database.

CREATE TYPE gender_t     AS ENUM ('WOMAN', 'MAN', 'NON_BINARY', 'NOT_SHARED');
CREATE TYPE topic_t      AS ENUM ('OFFICE_LIFE', 'BOSS_RADAR', 'CANTEEN', 'CAKE_ALERT', 'HIRING_BUZZ');
CREATE TYPE claim_t      AS ENUM ('OPINION', 'RUMOUR');           -- only a RUMOUR can get a receipt
CREATE TYPE belief_t     AS ENUM ('PAKKI', 'GAPPA');               -- believe-o-meter vote
CREATE TYPE outcome_t    AS ENUM ('CAME_TRUE', 'BUSTED');
CREATE TYPE resolution_t AS ENUM ('PENDING', 'CAME_TRUE', 'BUSTED', 'UNCLEAR');
CREATE TYPE weather_t    AS ENUM ('SUNNY', 'CLOUDY', 'STORMY', 'FROZEN');

-- ---------------------------------------------------------------- identity

CREATE TABLE users (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    phone_token  CHAR(64)    NOT NULL UNIQUE,   -- hex HMAC-SHA256 of the E.164 number. Never the number.
    alias        VARCHAR(40) NOT NULL UNIQUE,   -- the funny secret name, e.g. "Sneaky Puchka #482"
    gender       gender_t    NOT NULL DEFAULT 'NOT_SHARED',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    msgs_sent    INTEGER     NOT NULL DEFAULT 0, -- a counter only. Chat content is end-to-end encrypted.
    banned_at    TIMESTAMPTZ
);

-- One row per calendar day a user opened the app. "Days used" is the row count.
CREATE TABLE user_days (
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day     DATE NOT NULL,
    PRIMARY KEY (user_id, day)
);

-- One-time passwords. Only a keyed MAC of the code is stored, never the code or the number.
CREATE TABLE otp_challenges (
    id           BIGSERIAL PRIMARY KEY,
    phone_token  CHAR(64)    NOT NULL,
    otp_mac      CHAR(64)    NOT NULL,
    expires_at   TIMESTAMPTZ NOT NULL,
    attempts     SMALLINT    NOT NULL DEFAULT 0,
    consumed     BOOLEAN     NOT NULL DEFAULT false,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_otp_phone ON otp_challenges (phone_token, created_at DESC);

-- Login sessions. Only the SHA-256 of the cookie token is stored, so a database leak cannot log anyone in.
CREATE TABLE sessions (
    token_hash CHAR(64)    PRIMARY KEY,
    user_id    UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions (user_id);

-- ---------------------------------------------------------------- feed

CREATE TABLE posts (
    id               UUID PRIMARY KEY,                 -- generated by the app, used as AES-GCM associated data
    author_id        UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    topic            topic_t     NOT NULL,
    claim            claim_t     NOT NULL DEFAULT 'OPINION',
    body_ct          BYTEA       NOT NULL,             -- AES-256-GCM ciphertext (includes the tag)
    body_iv          BYTEA       NOT NULL,
    key_id           SMALLINT    NOT NULL,             -- which data key sealed it, so keys can rotate
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Rumour Receipts
    settle_opens_at  TIMESTAMPTZ NOT NULL,             -- earliest time the author can ask for a verdict
    proposed_outcome outcome_t,                         -- the author's guess. It only opens the vote.
    proposed_at      TIMESTAMPTZ,                       -- set when the community vote opens
    resolution       resolution_t NOT NULL DEFAULT 'PENDING',
    resolved_at      TIMESTAMPTZ,
    removed_at       TIMESTAMPTZ,
    CONSTRAINT only_rumours_get_receipts CHECK (claim = 'RUMOUR' OR (proposed_at IS NULL AND resolution = 'PENDING'))
);
CREATE INDEX idx_posts_recent  ON posts (created_at DESC) WHERE removed_at IS NULL;
CREATE INDEX idx_posts_author  ON posts (author_id);
CREATE INDEX idx_posts_voting  ON posts (proposed_at) WHERE resolution = 'PENDING' AND proposed_at IS NOT NULL;

-- A view counts once per person per post, so refreshing cannot inflate it.
CREATE TABLE post_views (
    post_id   UUID NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id   UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    viewed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (post_id, user_id)
);

CREATE TABLE post_likes (
    post_id UUID NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (post_id, user_id)
);
CREATE INDEX idx_likes_user ON post_likes (user_id);

-- Believe-o-meter: Pakki khabar (solid news) or Gappa (tall tale).
CREATE TABLE belief_votes (
    post_id UUID     NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id UUID     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    vote    belief_t NOT NULL,
    PRIMARY KEY (post_id, user_id)
);

-- Rumour Receipts: the community decides what happened. The author never settles their own rumour.
CREATE TABLE receipt_votes (
    post_id  UUID        NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    voter_id UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    outcome  outcome_t   NOT NULL,
    voted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (post_id, voter_id)
);

CREATE TABLE reports (
    id          BIGSERIAL PRIMARY KEY,
    post_id     UUID         NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    reporter_id UUID         NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason      VARCHAR(200) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (post_id, reporter_id)
);

-- ---------------------------------------------------------------- chat and rooms

CREATE TABLE conversations (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_a     UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_b     UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (user_a < user_b),                -- store each pair once
    UNIQUE (user_a, user_b)
);

-- The server only ever holds ciphertext. A message is deleted after it is read,
-- unless BOTH people chose to keep it.
CREATE TABLE chat_envelopes (
    id              BIGSERIAL PRIMARY KEY,
    conversation_id UUID        NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id       UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    ciphertext      BYTEA       NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at         TIMESTAMPTZ,
    expires_at      TIMESTAMPTZ,            -- set when read_at is set
    keep_sender     BOOLEAN     NOT NULL DEFAULT false,
    keep_receiver   BOOLEAN     NOT NULL DEFAULT false
);
CREATE INDEX idx_envelopes_conv ON chat_envelopes (conversation_id, created_at);

-- Screenshot permission is given by the person whose messages would be captured.
CREATE TABLE screenshot_permissions (
    conversation_id UUID        NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    grantor_id      UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    allowed         BOOLEAN     NOT NULL DEFAULT false,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (conversation_id, grantor_id)
);

CREATE TABLE rooms (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name        VARCHAR(40) NOT NULL,
    save_chat   BOOLEAN     NOT NULL DEFAULT true,
    invite_code CHAR(9)     NOT NULL UNIQUE,   -- like "abcd-2345", the tail of the invite link
    created_by  UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE room_members (
    room_id   UUID        NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    user_id   UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (room_id, user_id)
);

-- ---------------------------------------------------------------- jobs information

CREATE TABLE companies (
    id          SERIAL PRIMARY KEY,
    name        VARCHAR(80) NOT NULL UNIQUE,
    sector      VARCHAR(40) NOT NULL,
    city        VARCHAR(40) NOT NULL,
    weather     weather_t   NOT NULL,           -- hiring weather
    openings    INTEGER     NOT NULL DEFAULT 0 CHECK (openings >= 0),
    avg_days    INTEGER     NOT NULL CHECK (avg_days > 0),
    toughness   SMALLINT    NOT NULL CHECK (toughness BETWEEN 1 AND 5),
    fresher_band VARCHAR(40) NOT NULL,
    mid_band     VARCHAR(40) NOT NULL,
    referral     VARCHAR(60) NOT NULL,
    notice       VARCHAR(60) NOT NULL,
    roles        VARCHAR(120) NOT NULL,          -- comma separated, short list
    is_sample    BOOLEAN     NOT NULL DEFAULT false,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE company_steps (
    company_id INTEGER      NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    ord        SMALLINT     NOT NULL,
    name       VARCHAR(60)  NOT NULL,
    detail     VARCHAR(160) NOT NULL,
    PRIMARY KEY (company_id, ord)
);
CREATE TABLE company_whispers (
    id         BIGSERIAL PRIMARY KEY,
    company_id INTEGER      NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    author_id  UUID         REFERENCES users(id) ON DELETE SET NULL,  -- null for seeded samples
    body       VARCHAR(280) NOT NULL,
    pakki      INTEGER      NOT NULL DEFAULT 0,
    gappa      INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_whispers_company ON company_whispers (company_id, created_at DESC);
